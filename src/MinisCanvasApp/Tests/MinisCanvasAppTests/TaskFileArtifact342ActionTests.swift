import Foundation
import Testing
import MinisCore
@testable import MinisCanvasApp

@Suite("D-TASK-12 typed file actions and exact preview bytes")
@MainActor
struct TaskFileArtifact342ActionTests {
    @Test("real generated bytes open and reveal through existing actions without ActionRecord fabrication")
    func successfulTypedFileActions() throws {
        let f = try TaskFileArtifact342Fixture()
        let navigation = try f.navigation()
        let access = try #require(f.consumer.fileArtifactAccess(navigation: navigation))
        var actions: [String] = []
        for intent in [AgentFileOutputIntent.systemOpen, .finderReveal, .copySafePath] {
            let result = AgentFileOutputActionConsumer.performTaskArtifact(
                access: access,
                validateBinding: { [consumer = f.consumer] in consumer.fileArtifactAccess(navigation: navigation) == access },
                authorizeTarget: { [consumer = f.consumer] in consumer.fileArtifactTargetAuthorized(navigation: navigation, target: $0) },
                intent: intent, probe: AgentFileOutputTargetResolver.fileSystemProbe,
                digest: { AgentFileOutputTargetResolver.generatedFileDigest($0) },
                open: { actions.append("open:\($0.lastPathComponent)"); return true },
                reveal: { actions.append("reveal:\($0.lastPathComponent)"); return true },
                copy: { actions.append("copy:\(URL(fileURLWithPath: $0).lastPathComponent)"); return true }
            )
            #expect(result == .completed)
        }
        #expect(actions == ["open:result.md", "reveal:result.md", "copy:result.md"])
    }

    @Test("changed, missing, and project-escaping files never invoke an OS action", arguments: ["changed", "missing", "escape"])
    func changedMissingOrEscapedFileIsRejected(mode: String) throws {
        let f = try TaskFileArtifact342Fixture()
        let navigation = try f.navigation()
        let access = try #require(f.consumer.fileArtifactAccess(navigation: navigation))
        let expected: AgentFileOutputFailure
        switch mode {
        case "changed":
            try Data("different bytes342".utf8).write(to: f.file)
            expected = .stale
        case "missing":
            try FileManager.default.removeItem(at: f.file)
            expected = .missing
        default:
            let outside = f.root.appendingPathComponent("outside-project.md")
            try Data("synthetic generated file342\n".utf8).write(to: outside)
            try FileManager.default.removeItem(at: f.file)
            try FileManager.default.createSymbolicLink(at: f.file, withDestinationURL: outside)
            expected = .outOfBounds
        }
        var calls = 0
        let result = AgentFileOutputActionConsumer.performTaskArtifact(
            access: access, validateBinding: { [consumer = f.consumer] in consumer.fileArtifactAccess(navigation: navigation) == access },
            authorizeTarget: { [consumer = f.consumer] in consumer.fileArtifactTargetAuthorized(navigation: navigation, target: $0) },
            intent: .systemOpen, probe: AgentFileOutputTargetResolver.fileSystemProbe,
            digest: { AgentFileOutputTargetResolver.generatedFileDigest($0) },
            open: { _ in calls += 1; return true }, reveal: { _ in calls += 1; return true },
            copy: { _ in calls += 1; return true }
        )
        #expect(result == .failed(expected))
        #expect(calls == 0)
    }

    @Test("a newly denied child path blocks the historical successful artifact before hashing")
    func currentTargetDenialIsNotAStoredDirectoryGrant() throws {
        let f = try TaskFileArtifact342Fixture()
        let navigation = try f.navigation()
        let access = try #require(f.consumer.fileArtifactAccess(navigation: navigation))
        let current = BuiltinToolExecutor(allowedRoot: f.root, deniedRoots: [f.file.deletingLastPathComponent()])
        #expect(try current.validatedTargetWorkspaceDirectory(f.project.path) == f.project)
        f.consumer.bindFileArtifacts(ledger: f.ledger, facts: f.facts,
            targetValidator: current.fileArtifactTargetValidator(), projectValidator: { _, _ in true })
        #expect(f.consumer.fileArtifactAccess(navigation: navigation) == access)
        #expect(!f.consumer.fileArtifactPresentationAuthorized(navigation: navigation, target: f.file))
        var ioAndActions = 0
        let result = AgentFileOutputActionConsumer.performTaskArtifact(
            access: access, validateBinding: { [consumer = f.consumer] in consumer.fileArtifactAccess(navigation: navigation) == access },
            authorizeTarget: { [consumer = f.consumer] in consumer.fileArtifactTargetAuthorized(navigation: navigation, target: $0) },
            intent: .systemOpen, probe: AgentFileOutputTargetResolver.fileSystemProbe,
            digest: { _ in ioAndActions += 1; return navigation.outputSHA256 },
            open: { _ in ioAndActions += 1; return true }, reveal: { _ in ioAndActions += 1; return true },
            copy: { _ in ioAndActions += 1; return true }
        )
        #expect(result == .failed(.outOfBounds))
        #expect(ioAndActions == 0)
    }

    @Test("renaming the pathname after opening cannot publish proof for a different descriptor")
    func pathReplacementInvalidatesOpenedDescriptor() throws {
        let f = try TaskFileArtifact342Fixture()
        let handle = try #require(AgentFileOutputTargetResolver.generatedFileHandle(f.file))
        defer { try? handle.close() }
        #expect(AgentFileOutputTargetResolver.generatedFileStillMatches(handle, url: f.file))
        let moved = f.file.deletingLastPathComponent().appendingPathComponent("old-result.md")
        try FileManager.default.moveItem(at: f.file, to: moved)
        try Data("synthetic generated file342\n".utf8).write(to: f.file)
        #expect(!AgentFileOutputTargetResolver.generatedFileStillMatches(handle, url: f.file))
    }

    @Test("preview returns only bytes whose actual descriptor read matches the generated SHA")
    func previewChecksActualReadAndCurrentBinding() throws {
        let f = try TaskFileArtifact342Fixture()
        let navigation = try f.navigation()
        let access = try #require(f.consumer.fileArtifactAccess(navigation: navigation))
        let root = URL(fileURLWithPath: navigation.binding.workingDirectory, isDirectory: true)
        let good = FilePreview.loadAgentOutput(url: f.file, workspaceRoot: root,
            expectedSHA256: navigation.outputSHA256,
            validateBinding: { [consumer = f.consumer] in consumer.fileArtifactAccess(navigation: navigation) == access },
            authorizeTarget: { [consumer = f.consumer] in consumer.fileArtifactTargetAuthorized(navigation: navigation, target: $0) })
        #expect(good.error == nil && good.text == "synthetic generated file342\n")
        try Data("changed after generation342".utf8).write(to: f.file)
        let stale = FilePreview.loadAgentOutput(url: f.file, workspaceRoot: root,
            expectedSHA256: navigation.outputSHA256,
            validateBinding: { [consumer = f.consumer] in consumer.fileArtifactAccess(navigation: navigation) == access },
            authorizeTarget: { [consumer = f.consumer] in consumer.fileArtifactTargetAuthorized(navigation: navigation, target: $0) })
        #expect(stale.text == nil && stale.error == AgentFileOutputFailure.stale.message)
        try Data("synthetic generated file342\n".utf8).write(to: f.file)
        let invalidator = TaskFilePreview342Invalidator(consumer: f.consumer, navigation: navigation)
        let invalidated = FilePreview.loadAgentOutput(url: f.file, workspaceRoot: root,
            expectedSHA256: navigation.outputSHA256,
            validateBinding: { [consumer = f.consumer] in consumer.fileArtifactAccess(navigation: navigation) == access },
            authorizeTarget: { invalidator.authorize($0) })
        #expect(invalidated.text == nil && invalidated.error != nil)
        #expect(f.consumer.fileArtifactAccess(navigation: navigation) == nil)
    }
}

private final class TaskFilePreview342Invalidator: @unchecked Sendable {
    private let lock = NSLock()
    private var calls = 0
    private let consumer: TaskCenterControlConsumer
    private let navigation: TaskCenterFileArtifactNavigation
    init(consumer: TaskCenterControlConsumer, navigation: TaskCenterFileArtifactNavigation) {
        self.consumer = consumer; self.navigation = navigation
    }
    func authorize(_ url: URL) -> Bool {
        lock.lock(); calls += 1; let invalidate = calls == 2; lock.unlock()
        if invalidate {
            consumer.bindFileArtifacts(ledger: nil, facts: nil)
            return false
        }
        return consumer.fileArtifactTargetAuthorized(navigation: navigation, target: url)
    }
}
