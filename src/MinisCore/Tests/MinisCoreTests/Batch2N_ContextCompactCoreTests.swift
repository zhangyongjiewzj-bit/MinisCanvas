/// 第二批线 N（RED，Core 部分）。
/// 2) 自动压缩（AgentLoop 预算 .autoCompact）不再因工具往来拒绝：现状 AgentLoop.swift:2888-2895 用
///    .requireVerbatimText 且不传 provider，工具往来无法逐字表示即抛 compactionCheckpointUnavailable
///    （F19AgentFixTests.autoCompactRefusesUnrepresentableToolEffectsBeforeAnotherProviderCall 现正断言这个抛错，需改）。
/// 3a) 模型可见的 context_compact 工具：AgentToolCatalog.nativeDefinitions()（AgentToolCatalog.swift:241）目前没有。

private final class Batch2NLoopProvider: LLMProvider, @unchecked Sendable {
    var name: String { "Batch2NLoop" }
    var model: LLMModel = .claudeHaiku45
    var capabilities: Set<ProviderCapability> { [.tools] }
    private let lock = NSLock()
    private var dialogue: [[LLMMessage]] = []
    private var summaries: [[LLMMessage]] = []
    var dialogueRequests: [[LLMMessage]] { lock.withLock { dialogue } }
    var summaryRequests: [[LLMMessage]] { lock.withLock { summaries } }

    private static func toolCall(id: String) -> LLMToolCall {
        LLMToolCall(id: id, name: "web_search",
                    rawArguments: #"{"query":"x"}"#, arguments: ["query": "x"])
    }

    /// 无工具重载 = 摘要请求（与 CompactionProductionFactConsumerTests 的 FactContextProvider 同约定）。
    func sendMessage(messages: [LLMMessage], systemPrompt: String?, maxTokens: Int,
                     temperature: Double?) async throws -> LLMResponse {
        lock.withLock { summaries.append(messages) }
        return LLMResponse(text: "B2N-LOOP-SUMMARY：旧问题与两次 web_search 检索已完成。", stopReason: nil, usage: nil)
    }

    func sendMessage(messages: [LLMMessage], systemPrompt: String?, tools: [AgentToolDefinition],
                     maxTokens: Int, temperature: Double?) async throws -> LLMResponse {
        let ordinal = lock.withLock { dialogue.append(messages); return dialogue.count }
        let usage = LLMUsage(inputTokens: 20, outputTokens: 10)
        switch ordinal {
        case 1: return LLMResponse(text: "", stopReason: nil, usage: usage, toolCalls: [Self.toolCall(id: "b2n-c1")])
        case 2: return LLMResponse(text: "", stopReason: nil, usage: usage, toolCalls: [Self.toolCall(id: "b2n-c2")])
        default: return LLMResponse(text: "r3 收尾", stopReason: nil, usage: usage)
        }
    }

    func streamMessage(messages: [LLMMessage], systemPrompt: String?, maxTokens: Int,
                       temperature: Double?) async throws -> AsyncThrowingStream<LLMStreamChunk, Error> {
        AsyncThrowingStream { $0.finish() }
    }
}

private final class Batch2NBulkyExecutor: ToolExecutor, @unchecked Sendable {
    private(set) var callCount = 0
    func execute(name: String, input: [String: Any]) async throws -> String {
        callCount += 1
        return (0..<30).map { "检索结果 \(callCount)-\($0)：独立内容 \($0 * 13 + callCount)，用于撑大体积。" }.joined(separator: "\n")
    }
}

private func bulkyText(_ tag: String) -> String {
    (0..<30).map { "\(tag) 第 \($0) 行：独立内容 \($0 * 19 + tag.count)。" }.joined(separator: "\n")
}

private func characters(_ messages: [LLMMessage]) -> Int { messages.reduce(0) { $0 + $1.content.count } }

// The callback owns the frozen closed history. Tool exchanges generated by
// this run are carried as an exact runtime suffix, as at the App boundary.
func batch2CanonicalCompaction(
    source: [LLMMessage], provider: any LLMProvider & Sendable
) -> AgentLoop.AutomaticCompaction {
    { sessionID, current, compactor in
        try #require(Array(current.prefix(source.count)) == source)
        let runtime = Array(current.dropFirst(source.count))
        let result = try await LossySummaryCompaction.compact(
            messages: source, keepRecent: compactor.keepRecentMessages, provider: provider)
        let replacement = result.messages + runtime
        guard result.refusalReason == nil, result.compactedCount > 0,
              Compactor.hasMaterialRequestReduction(from: current, to: replacement) else {
            throw AgentLoopError.compactionCheckpointUnavailable("no verified request reduction")
        }
        let checkpoint = try CompactionCheckpoint.makeProjection(
            sessionID: sessionID, sourceTranscriptRevision: 0, sourceMessages: source, result: result)
        return AgentLoop.AutomaticCompactionTransition(
            checkpoint: checkpoint, sourcePrefix: source, liveSuffix: [],
            runtimeSuffix: runtime, messages: replacement)
    }
}

@Suite("Batch2N automatic compaction and context_compact tool")
struct Batch2N_ContextCompactCoreTests {
    /// RED 2：自动压缩遇到工具往来 → 不抛、请求模型摘要、下一轮历史变小并带摘要，且没有孤儿 tool_result。
    @Test func autoCompactSummarizesToolExchangesInsteadOfRefusing() async throws {
        let tracker = BudgetTracker(RequestBudget(maxTokensPerSession: 50, overBudgetPolicy: .autoCompact))
        let provider = Batch2NLoopProvider()
        let executor = Batch2NBulkyExecutor()
        let root = try minisCoreToolContractRoot("b2n-auto-compact")
        defer { try? FileManager.default.removeItem(at: root) }
        let source = [
            LLMMessage(role: .user, content: bulkyText("旧问题1")),
            LLMMessage(role: .assistant, content: bulkyText("旧回答1"), toolCalls: [
                LLMToolCall(id: "historical-search", name: "web_search",
                            rawArguments: #"{"query":"owned synthetic note"}"#,
                            arguments: ["query": "owned synthetic note"])
            ]),
            LLMMessage(role: .tool, content: bulkyText("旧检索结果"), toolCallID: "historical-search"),
            LLMMessage(role: .user, content: bulkyText("旧问题2"))
        ]
        // web_search 默认要问（11/19）；这里测的是压缩，检索工具显式设为自动通过。
        var loop = AgentLoop(maxIterations: 5,
                             approvalGate: ApprovalGate(policyByTool: ["web_search": .autoApprove]),
                             loopDetector: nil, requestBudget: tracker,
                             compactor: Compactor(keepRecentMessages: 1),
                             toolExecutionFactLedger: try minisCoreToolContractLedger(at: root))
        loop.automaticCompaction = batch2CanonicalCompaction(source: source, provider: provider)

        let identity = minisCoreToolContractIdentity("b2n-auto-compact", sessionID: "b2n-auto-compact")
        let result = try await loop.run(
            messages: source,
            systemPrompt: nil, provider: provider, toolExecutor: executor,
            tools: minisCoreToolContractCatalog(["web_search"]),
            currentConversationID: identity.turn.sessionID,
            executionIdentity: identity)

        #expect(result.messages.last?.content == "r3 收尾")
        #expect(executor.callCount == 2)
        // 仅已关闭的旧检索交给模型摘要，本轮两次工具往来保持原样。
        let summaryInput = provider.summaryRequests.first?.map(\.content).joined(separator: "\n") ?? ""
        #expect(!provider.summaryRequests.isEmpty)
        #expect(summaryInput.contains("web_search"))
        // 压缩后的第 3 次对话请求：带摘要、体积小于压缩前的第 2 次请求。
        let requests = provider.dialogueRequests
        try #require(requests.count == 3)
        #expect(requests[2].contains { $0.content.contains("B2N-LOOP-SUMMARY") })
        #expect(characters(requests[2]) < characters(requests[1]))
        // 请求内每个 tool_result 都有同请求内的 tool_use。
        let calls = requests[2].flatMap(\.toolCalls)
        let uses = Set(calls.map(\.id))
        let results = requests[2].filter { $0.role == .tool }.compactMap(\.toolCallID)
        let expectedIDs: Set<String> = ["b2n-c1", "b2n-c2"]
        #expect(calls.count == expectedIDs.count && uses == expectedIDs)
        #expect(results.count == expectedIDs.count && Set(results) == expectedIDs)
        #expect(Set(results).isSubset(of: uses), "截断边界不能拆开 tool_use / tool_result")
    }

    /// RED 3a：目录里有模型可调用的 context_compact，说明里让模型知道它是“压缩上下文”。
    @Test func catalogOffersContextCompactTool() throws {
        let tool = try #require(AgentToolCatalog.makeTools().first { $0.name == "context_compact" },
                                "用户说“压缩上下文”时模型回答“没有这个工具”：目录缺 context_compact")
        #expect(tool.description.localizedCaseInsensitiveContains("compact"))
        #expect(AgentToolCatalog.implementedNativeToolNames.contains("context_compact"))
    }
}
